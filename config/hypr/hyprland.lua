-- =============================================================================
-- Hyprland config (Lua). Hyprland >= 0.57 dropped hyprland.conf support.
-- Migrated from hyprland.conf / looknfeel.conf / keybinds.conf on 2026-11-15.
-- Those .conf files are kept only for reference/rollback and are NOT loaded.
--
-- Layout:
--   hyprland.lua                  this file: plugins, monitors, autostart
--   looknfeel.lua                 general/decoration/animations/rules + hy3 opts
--   keybinds.lua                  all binds (parsed by scripts/keybinds_parser.py)
--   monitors.lua                  generated by nwg-displays (do not edit)
--   wallust/colors-hyprland.lua   generated by wallust (do not edit)
--
-- hyprlock/hypridle still use hyprlang (.conf) and are unaffected; hyprlock keeps
-- reading wallust/colors-hyprland.conf.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Plugins
-- ---------------------------------------------------------------------------
-- hyprpm-managed (compiled) plugins: hy3 (+ hyprEasymotion if it ever builds).
-- `hyprpm reload` loads every ENABLED plugin that matches this Hyprland build
-- and skips incompatible ones instead of crashing. The trailing `hyprctl reload`
-- re-runs this config AFTER the plugins exist, so the plugin-guarded blocks in
-- looknfeel.lua / keybinds.lua switch on. The `hyprland.start` event fires once
-- per session, so the reload does not loop.
hl.on("hyprland.start", function()
    hl.exec_cmd("hyprpm reload -n && hyprctl reload")
end)

-- split-monitor-workspaces is now a pure-Lua library (no hyprpm/.so). It lives
-- outside the dotfiles repo, pinned to the tag matching Hyprland:
--   git -C ~/.local/share/hypr-plugins/split-monitor-workspaces fetch --tags
--   git -C ~/.local/share/hypr-plugins/split-monitor-workspaces checkout v0.57.x
-- It's loaded via its init.lua so its internal modules are namespaced
-- (its lua/monitors.lua would otherwise collide with our nwg-displays monitors.lua).
local plugin_root = os.getenv("HOME") .. "/.local/share/hypr-plugins"
package.path = package.path .. ";" .. plugin_root .. "/?/init.lua;" .. plugin_root .. "/?.lua"

local ok_smw, smw = pcall(require, "split-monitor-workspaces")
if ok_smw then
    -- Unified cross-monitor workspaces (GNOME-like): each monitor gets its own
    -- 1-10 range (DP-1: 1-10, DP-2: 11-20) but link_monitors switches both
    -- together, so "desktop N" spans both screens.
    smw.setup({
        workspace_count = 10,
        monitor_priority = { "DP-1", "DP-2" },
        keep_focused = false,
        enable_notifications = false,
        enable_persistent_workspaces = true,
        enable_wrapping = false,
        link_monitors = true,
    })
else
    smw = nil
    hl.notification.create({
        text = "split-monitor-workspaces not found; using plain workspaces",
        timeout = 8000,
    })
end

-- Shared with the other modules (they read it via the global table).
PLUGINS = {
    hy3 = hl.plugin.hy3,     -- nil until hyprpm has loaded hy3
    smw = smw,
    easymotion = hl.plugin.easymotion,
}

