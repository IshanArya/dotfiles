-- ---------------------------------------------------------------------------
-- Autostart
-- ---------------------------------------------------------------------------
hl.on("hyprland.start", function()
    hl.exec_cmd("waybar")
    hl.exec_cmd("swaync")
    hl.exec_cmd("hypridle")
    hl.exec_cmd("sunsetr")
    hl.exec_cmd("swayosd-server")
    -- Start the wallpaper daemon first so it binds the correct ($WAYLAND_DISPLAY)
    -- socket, then start darkman in-session. darkman inherits Hyprland's
    -- environment here (WAYLAND_DISPLAY, HYPRLAND_INSTANCE_SIGNATURE,
    -- XDG_CURRENT_DESKTOP), so its startup hook fires theme-switch.sh against the
    -- live socket instead of wayland-0. (darkman.service is intentionally
    -- disabled; do not re-enable it.)
    --
    -- Caching is intentionally LEFT ON (no --no-cache): on NVIDIA-only cold boot
    -- the DRM outputs aren't render-ready when theme-switch.sh's `awww img` fires,
    -- so that paint is dropped; with caching on, awww repaints from cache once
    -- DP-1/DP-2 are ready. theme-switch.sh still sets the authoritative wallpaper.
    hl.exec_cmd("awww-daemon")
    -- Re-assert the current-mode wallpaper on every output (re)creation (guards
    -- the awww cache-restore race and DPMS/cable reconnects). Requires socat.
    hl.exec_cmd(os.getenv("HOME") .. "/.config/hypr/scripts/monitor-wallpaper-listener.sh")
    hl.exec_cmd("darkman run")
end)
